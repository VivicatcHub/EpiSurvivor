export function getPublicListings(filters: ListingFilters = {}): Listing[] {
  const q = filters.q?.trim().toLowerCase();

  return LISTINGS.filter((listing) => {
    if (listing.status !== "publiee") return false;
    if (
      filters.contract &&
      filters.contract !== "toutes" &&
      listing.contract !== filters.contract
    ) {
      return false;
    }
    if (!q) return true;
    return [listing.title, listing.company, listing.city, ...listing.skills]
      .join(" ")
      .toLowerCase()
      .includes(q);
  });
}

export function getListing(id: string): Listing | undefined {
  return LISTINGS.find((listing) => listing.id === id);
}

export function getCompanyListings(companyId: string): Listing[] {
  return LISTINGS.filter((listing) => listing.companyId === companyId);
}

export function getApplicationsForSeeker(seekerId: string): Application[] {
  return APPLICATIONS.filter(
    (application) => application.seekerId === seekerId,
  );
}

export function getApplicationsForCompany(companyId: string): Application[] {
  const listingIds = new Set(
    getCompanyListings(companyId).map((listing) => listing.id),
  );
  return APPLICATIONS.filter((application) =>
    listingIds.has(application.listingId),
  );
}
